import { CalendarDays, Pencil, Receipt, Repeat, Trash2, Wallet, X } from 'lucide-react'
import { formatDate, formatLabel, formatMoney } from '../../lib/format'
import type { CalendarEvent } from '../../types'
import { Button } from '../Button'
import { IconButton } from '../IconButton'
import { IconCircle } from '../IconCircle'
import { Modal } from '../Modal'
import { StatusBadge } from '../StatusBadge'
import { getEventStatus, getEventStyle } from './eventStyles'

interface EventDetailsProps {
  event: CalendarEvent
  today: string
  onClose: () => void
  onShowOnCalendar: (event: CalendarEvent) => void
  onEdit: (event: CalendarEvent) => void
  onDelete: (event: CalendarEvent) => void
  onRecordPayment: (event: CalendarEvent) => void
  onEditSchedule: () => void
  onViewTransaction: () => void
}

/** Details of a calendar entry with its actions. Recurring occurrences are edited through their schedule. */
export function EventDetails({ event, today, onClose, onShowOnCalendar, onEdit, onDelete, onRecordPayment, onEditSchedule, onViewTransaction }: EventDetailsProps) {
  const { icon, tone } = getEventStyle(event.kind)
  const status = getEventStatus(event, today)
  const recurring = event.source === 'recurring'
  const income = event.type === 'income'

  function onShowClick() {
    onShowOnCalendar(event)
  }

  function onEditClick() {
    onEdit(event)
  }

  function onDeleteClick() {
    onDelete(event)
  }

  function onRecordClick() {
    onRecordPayment(event)
  }

  return (
    <Modal title={event.title} onClose={onClose} width="w-[680px]">
      <div className="absolute top-4 right-4">
        <IconButton icon={X} label="Close details" onClick={onClose} />
      </div>
      <div className="mt-4 flex items-center gap-4">
        <IconCircle icon={icon} tone={tone} size="md" />
        <div className="flex-1">
          <p className="text-2xl font-bold tracking-tight text-ink">{formatMoney(event.amountCents)}</p>
          <p className="text-sm text-muted">
            {formatDate(event.date, 'weekdayLong')}, {event.date.slice(0, 4)} · {formatLabel(event.kind)}
          </p>
        </div>
        <StatusBadge status={status.key} label={status.label} tone={status.tone} />
      </div>
      {recurring && (
        <p className="mt-3 flex items-center gap-1.5 text-sm text-muted">
          <Repeat className="size-4" strokeWidth={2} aria-hidden />
          Generated by a recurring schedule.
        </p>
      )}

      <p className="mt-4 text-sm text-muted">
        Recording adds one transaction to your ledger. If you already entered this payment manually, do not record it again. Deleting an
        event or schedule keeps existing transactions.
      </p>
      {event.skipped && (
        <p className="mt-2 text-sm text-muted">
          This transaction was deleted. It will not be regenerated by recurring synchronization; add a manual transaction if you need to
          record it again.
        </p>
      )}

      <div className="mt-6 flex items-center gap-3">
        {!recurring && (
          <Button variant="danger" icon={Trash2} onClick={onDeleteClick}>
            Delete
          </Button>
        )}
        <div className="ml-auto flex flex-wrap justify-end gap-3">
          <Button variant="outline" icon={CalendarDays} onClick={onShowClick}>
            Show on calendar
          </Button>
          {event.transactionId && (
            <Button variant="outline" icon={Receipt} onClick={onViewTransaction}>
              View transaction
            </Button>
          )}
          {recurring ? (
            <Button variant="outline" icon={Repeat} onClick={onEditSchedule}>
              Edit recurring schedule
            </Button>
          ) : (
            <Button variant="outline" icon={Pencil} onClick={onEditClick}>
              Edit
            </Button>
          )}
          {!status.settled && (
            <Button icon={Wallet} onClick={onRecordClick}>
              {income ? 'Record income received' : 'Record payment'}
            </Button>
          )}
        </div>
      </div>
    </Modal>
  )
}
